import test from "node:test";
import assert from "node:assert/strict";
import * as fs from "node:fs/promises";
import path from "node:path";
import { load as yaml } from "js-yaml";
import { sampleSetups, generateSamples } from "../../scripts/generate-samples.js";
import { projects, capabilities, standards, tools } from "../../src/components/registry.js";
import { normalizeRequest, resolve } from "../../src/generator/resolve.js";
import { packageGraph } from "../../src/generator/package-graph.js";
import { plan } from "../../src/generator/plan.js";
import { temporary, read, readJson } from "../helpers.js";

/**
 * Read every catalog file to compare generated bytes across repeated runs.
 *
 * @param {string} root Absolute sample catalog root.
 * @returns {Promise<Object<string, string>>} File contents keyed by relative path.
 */
async function contents(root) {
  const result = {};
  const entries = await fs.readdir(root, { recursive: true, withFileTypes: true });

  for (const entry of entries) {
    if (!entry.isFile()) continue;

    const filename = path.join(entry.parentPath, entry.name);

    result[path.relative(root, filename)] = await fs.readFile(filename, "utf8");
  }

  return result;
}

test("sample catalog automatically includes newly registered components", () => {
  const entries = sampleSetups({
    projects: { ...projects, added: { ...projects.node, id: "added" } },
    capabilities: { ...capabilities, added: { ...capabilities.react, id: "added" } },
    standards: {
      ...standards,
      javascript: { ...standards.javascript, added: { ...standards.javascript.community, id: "added" } },
    },
    tools: { ...tools, added: { ...tools.gitignore, id: "added" } },
  });

  assert(entries.some((item) => item.path === "added/default"));
  assert(entries.some((item) => item.input.capabilities?.includes("added")));
  assert(entries.some((item) => item.input.standards?.javascript === "added"));
  assert(entries.some((item) => item.input.tools?.includes("added")));
  assert(
    entries.find((item) => item.path === "layouts/workspaces").input.packages.some((item) => item.project === "added"),
  );
  assert.equal(new Set(entries.map((item) => item.path)).size, entries.length);
});

test("samples contain real CLI output and regeneration is deterministic", async (t) => {
  const root = await temporary(t);
  const destination = path.join(root, "samples");

  const entries = sampleSetups().filter((entry) =>
    [
      "wordpress-plugin/default",
      "wordpress-plugin/standards/php-community",
      "node/capabilities/all",
      "node/tools/webpack",
      "layouts/nested",
      "layouts/workspaces",
    ].includes(entry.path),
  );

  assert.equal(await generateSamples(destination, entries), entries.length);
  assert.match(await read(destination, "wordpress-plugin/default/phpcs.xml.dist"), /ref="WordPress"/);
  assert.match(await read(destination, "wordpress-plugin/standards/php-community/phpcs.xml.dist"), /ref="PSR12"/);
  assert.match(await read(destination, "node/tools/webpack/webpack.config.mjs"), /src\/index\.tsx/);
  assert.match(await read(destination, "node/capabilities/all/eslint.config.mjs"), /tseslint.configs.recommended/);

  const workspace = await readJson(destination, "layouts/workspaces/package.json");
  const hooks = yaml(await read(destination, "layouts/nested/lefthook.yml"));

  assert.deepEqual(workspace.workspaces, ["packages/*"]);
  assert.match(workspace.scripts.lint, /--workspace=/);
  assert.equal(hooks["pre-commit"].commands["packages/wordpress-plugin:eslint"].root, "packages/wordpress-plugin/");

  for (const entry of entries) {
    const directory = path.join(destination, entry.path);
    const request = normalizeRequest(await readJson(directory, ".configra.json"));
    const proposal = await plan(resolve(request, await packageGraph(directory, request)));

    assert.equal(proposal.conflicts.length, 0, entry.path);
    assert.equal(proposal.changes.length, 0, entry.path);
    await assert.rejects(fs.stat(path.join(directory, ".git")), { code: "ENOENT" });
  }

  const before = await contents(destination);

  await fs.mkdir(path.join(destination, "obsolete"));
  await fs.writeFile(path.join(destination, "obsolete", "old.txt"), "remove me\n");
  await generateSamples(destination, entries);
  assert.deepEqual(await contents(destination), before);
  assert.deepEqual(await fs.readdir(root), ["samples"]);
});

test("failed sample generation preserves the previous catalog", async (t) => {
  const root = await temporary(t);
  const destination = path.join(root, "samples");
  const valid = sampleSetups().find((entry) => entry.path === "node/default");

  await generateSamples(destination, [valid]);

  const before = await contents(destination);

  await assert.rejects(
    generateSamples(destination, [
      valid,
      { path: "broken", description: "Invalid setup", input: { project: "invalid" } },
    ]),
    /Unsupported project/,
  );
  assert.deepEqual(await contents(destination), before);
  assert.deepEqual(await fs.readdir(root), ["samples"]);
});
